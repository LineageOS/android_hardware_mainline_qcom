func (p *pilSquasher) SetImageVariation(ctx android.ImageInterfaceContext, variation string) {
	p.properties.ImageVariation = variation
}

func (p *pilSquasher) InstallInVendor() bool {
	return p.ModuleBase.InstallInVendor() ||
		p.properties.ImageVariation == android.VendorVariation
}

func (p *pilSquasher) InstallInVendorRamdisk() bool {
	return p.ModuleBase.InstallInVendorRamdisk() ||
		p.properties.ImageVariation == android.VendorRamdiskVariation
}

func (p *pilSquasher) getSubname() string {
	if p.properties.ImageVariation == android.VendorRamdiskVariation {
		return "." + android.VendorRamdiskVariation
	}
	return ""
}

func (p *pilSquasher) GenerateAndroidBuildActions(ctx android.ModuleContext) {
	if p.properties.Mdt == nil {
		ctx.PropertyErrorf("mdt", "must specify an MDT header file")
		return
	}
	mdtPath := android.PathForModuleSrc(ctx, proptools.String(p.properties.Mdt))
	if mdtPath.Ext() != ".mdt" {
		ctx.PropertyErrorf("mdt", "expected a .mdt file, got %q", mdtPath.Base())
		return
	}

	if len(p.properties.Srcs) == 0 {
		ctx.PropertyErrorf("srcs", "must specify at least one chunk file (.b00, .b01, etc.)")
		return
	}

	srcPaths := android.PathsForModuleSrc(ctx, p.properties.Srcs)
	for _, src := range srcPaths {
		if !chunkExtRegexp.MatchString(src.Ext()) {
			ctx.PropertyErrorf("srcs", "expected chunk files (.b00, .b01, etc.), got %q", src.Base())
			return
		}
	}

	stem := proptools.StringDefault(p.properties.Stem, ctx.ModuleName()+".mbn")
	p.outputFile = android.PathForModuleOut(ctx, stem)

	rule := android.NewRuleBuilder(pctx, ctx)
	cmd := rule.Command().BuiltTool("pil-squasher")
	cmd.Output(p.outputFile)
	cmd.Input(mdtPath)
	cmd.Implicits(srcPaths)
	rule.Build("pil_squasher", "Squashing firmware")

	p.installPath = android.PathForModuleInstall(ctx, "firmware")
	if subdir := proptools.String(p.properties.Relative_install_path); subdir != "" {
		p.installPath = p.installPath.Join(ctx, subdir)
	}

	ctx.InstallFile(p.installPath, p.outputFile.Base(), p.outputFile)
	ctx.SetOutputFiles(android.Paths{p.outputFile}, "")

	p.properties.SubName = p.getSubname()
}

func (p *pilSquasher) AndroidMkEntries() []android.AndroidMkEntries {
	if p.outputFile == nil {
		return nil
	}

	return []android.AndroidMkEntries{{
		Class:      "ETC",
		SubName:    p.properties.SubName,
		OutputFile: android.OptionalPathForPath(p.outputFile),
		ExtraEntries: []android.AndroidMkExtraEntriesFunc{
			func(ctx android.AndroidMkExtraEntriesContext, entries *android.AndroidMkEntries) {
				entries.SetPath("LOCAL_MODULE_PATH", p.installPath)
				entries.SetString("LOCAL_INSTALLED_MODULE_STEM", p.outputFile.Base())
			},
		},
	},
	}
}
