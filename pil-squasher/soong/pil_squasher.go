package pil_squasher

import (
	"regexp"

	"github.com/google/blueprint/proptools"

	"android/soong/android"
)

var (
	pctx           = android.NewPackageContext("android/soong/pil_squasher")
	chunkExtRegexp = regexp.MustCompile(`^\.b[0-9]{2}$`)
)

func init() {
	android.RegisterModuleType("pil_squasher", pilSquasherFactory)
	android.RegisterModuleType("pil_squasher_defaults", pilSquasherDefaultsFactory)

	pctx.Import("android/soong/android")
}

type pilSquasherProperties struct {
	// The MDT header file
	Mdt *string `android:"path"`

	// The chunks (.b00, .b01, etc.).
	Srcs []string `android:"path"`

	// Output file name. Defaults to {name}.mbn
	Stem *string

	// Install to a subdirectory of the install path
	Relative_install_path *string

	// The name of the image this module is built for
	ImageVariation string `blueprint:"mutated"`

	// Suffix for the name of Android.mk entries generated by this module
	SubName string `blueprint:"mutated"`
}

type pilSquasher struct {
	android.ModuleBase
	android.DefaultableModuleBase
	properties pilSquasherProperties

	outputFile  android.WritablePath
	installPath android.InstallPath
}

type pilSquasherDefaults struct {
	android.ModuleBase
	android.DefaultsModuleBase
	properties pilSquasherProperties
}

func pilSquasherFactory() android.Module {
	module := &pilSquasher{}
	module.AddProperties(&module.properties)
	android.InitAndroidArchModule(module, android.DeviceSupported, android.MultilibCommon)
	android.InitDefaultableModule(module)
	return module
}

func pilSquasherDefaultsFactory() android.Module {
	module := &pilSquasherDefaults{}
	module.AddProperties(&module.properties)
	android.InitDefaultsModule(module)
	return module
}

var _ android.ImageInterface = (*pilSquasher)(nil)

